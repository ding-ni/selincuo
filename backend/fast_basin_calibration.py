"""Metrics-only basin evaluation using the same runoff, routing and lake kernels.

This evaluator never manufactures forcing or flow.  Candidate calculations
avoid writing multi-gigabyte hourly state histories, while the selected result
is subsequently generated by the normal continuous simulation entry point.
"""
from copy import deepcopy

import numpy as np
import pandas as pd

from .fast_calibration import _sources
from .forcing import lake_precipitation_series
from .grid_simulation import PARTITIONS, anchor, unit_forcing
from .lake_calibration import response_slope
from .model_core import PARAMETER_NAMES, initial_states, parameters
from .routing import route_partition


class BasinEvaluator:
    """All land units, one shared parameter vector, frozen real forcing."""
    def __init__(self, source, request):
        if request.get('partitionParameters') or request.get('parameterTransfer', {}).get('mode') != 'duja-shared':
            raise ValueError('流域快速评价仅用于共享参数方案')
        self.request = deepcopy(request)
        self.source = source
        self.spatial = source['spatial']
        self.units = self.spatial['units']
        self.start, self.end = pd.Timestamp(request['start']), pd.Timestamp(request['end'])
        ids = np.flatnonzero((source['times'] >= self.start) & (source['times'] <= self.end))
        self.times = source['times'][ids]
        if (len(ids) < 25 or self.times[0] != self.start or self.times[-1] != self.end or
                not np.all(np.diff(self.times.asi8) == 3600 * 10**9)):
            raise ValueError('流域快速评价需要完整、连续的小时气象')
        observation = request['_observations']
        self.initial = (request['_fixedInitialization'] if '_fixedInitialization' in request
                        else anchor(request, observation, self.start, self.end))
        if not self.initial:
            raise ValueError('湖位筛选需要已确定的湖位起算')
        base = {**request['parameters'], 'lapseRate': 0.}
        from .land_precipitation import validate_manifest,validate_parameters
        self.land_correction = validate_manifest(source.get('manifest', {}))
        validate_parameters(self.land_correction,request['parameters'])
        rain, temp, evap = unit_forcing(self.spatial, source['arrays'], ids, base, {},self.land_correction,source['times'])
        if self.spatial.get('aggregation'):
            offsets = np.array([sum(m['areaWeight'] * m['elevationOffsetM'] for m in g['members'])
                                for g in self.spatial['aggregation']])
        else:
            offsets = np.array([u['elevation'] - self.spatial['grids'][u['gridIndex']]['referenceElevation']
                                for u in self.units])
        self.groups = {}
        for part in PARTITIONS:
            indexes = np.array([i for i, unit in enumerate(self.units) if unit['partition'] == part], dtype=int)
            if not len(indexes):
                continue
            units = [self.units[i] for i in indexes]
            self.groups[part] = {'units': units, 'rain': np.ascontiguousarray(rain[:, indexes]),
                'temperature': np.ascontiguousarray(temp[:, indexes]),
                'evaporation': np.ascontiguousarray(evap[:, indexes]),
                'offsets': np.ascontiguousarray(offsets[indexes]),
                'glaciers': np.array([u['kind'] == 'glacier' for u in units]),
                'areas': np.array([u['areaKm2'] for u in units])}
        weights = np.asarray(self.spatial['lakeWeights'])
        self.lake_rain = lake_precipitation_series(source['manifest'], self.spatial,
                                                   source['arrays'], source['times'], ids)
        self.lake_evaporation = source['arrays']['evaporation'][ids] @ weights
        self.lake_area = float(self.spatial['lakeAreaKm2']) * 1e6
        self.slope = response_slope(source, self.start, self.end, self.initial)

    def daily(self, values, cancelled=None):
        from .grid_simulation import lake_balance_hourly
        p = parameters(values)
        from .land_precipitation import validate_parameters
        validate_parameters(self.land_correction,p)
        routed = {}
        vector = np.array([p[k] for k in PARAMETER_NAMES], dtype=float)
        for part in PARTITIONS:
            if cancelled and cancelled():
                raise InterruptedError('已停止湖位筛选，已完成候选保留')
            group = self.groups.get(part)
            if not group:
                routed[part] = np.zeros(len(self.times))
                continue
            state = initial_states(group['units'], p, self.request.get('initialHydrology') or {})
            source_volumes, error = _sources(group['rain'], group['temperature'], group['evaporation'],
                group['offsets'], group['glaciers'], group['areas'], state, vector)
            if error > 1e-6:
                raise ValueError('候选产流过程水量不闭合')
            flow, _, _, _, _ = route_partition(source_volumes, {}, p,
                                               self.request.get('routingMode', 'source-separated'))
            routed[part] = flow
        q = {'duja': routed['duja'], 'zajia': routed['duja'] + routed['zajia_rest'],
             **{key: routed[key] for key in ('zagen', 'boqu', 'ali', 'fringe')}}
        q['total'] = sum(q[key] for key in ('zajia', 'zagen', 'boqu', 'ali', 'fringe'))
        lake_evap = self.lake_evaporation * p['lakeCoefficient']
        levels, volumes, continuous, flux, _, _ = lake_balance_hourly(
            self.times, q['total'], self.lake_rain, lake_evap, self.lake_area, self.initial)
        hourly = pd.DataFrame({**q, 'lakeLevel': levels, 'lakeRainMm': self.lake_rain,
            'lakeEvaporationMm': lake_evap, 'lakeDeltaVolumeM3': flux,
            'volumeChange': volumes, 'continuousLakeVolumeChange': continuous}, index=self.times)
        counts = hourly.total.resample('D', closed='right', label='left').count()
        daily = hourly[[*q, 'lakeLevel']].resample('D', closed='right', label='left').mean().where(counts.eq(24), axis=0)
        daily['lakeLevel'] = hourly.lakeLevel.resample('D', closed='right', label='left').mean().where(
            hourly.lakeLevel.resample('D', closed='right', label='left').count().eq(24))
        for key in ('lakeRainMm', 'lakeEvaporationMm', 'lakeDeltaVolumeM3'):
            daily[key] = hourly[key].resample('D', closed='right', label='left').sum(min_count=24)
        for key, values in {'lakeInflowM3': hourly.total * 3600,
                            'lakePrecipitationM3': hourly.lakeRainMm/1000*self.lake_area,
                            'lakeEvaporationM3': hourly.lakeEvaporationMm/1000*self.lake_area}.items():
            daily[key] = values.resample('D', closed='right', label='left').sum(min_count=24)
        daily = daily.loc[(daily.index >= self.start.normalize()) & (daily.index < self.end.ceil('D'))]
        daily['baseLevel'] = daily['lakeLevel']
        daily['slope'] = self.slope.reindex(daily.index)
        for key, name in [('level', 'observedLevel'), ('flow', 'observedFlow')]:
            observed = self.request['_observations'][key]
            daily[name] = pd.Series(list(observed.values()), index=pd.to_datetime(list(observed))).reindex(daily.index)
        return daily
